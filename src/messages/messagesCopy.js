export function messagesText(lang) {
  return messagesCopy[lang] || messagesCopy.en;
}

/** Libellé d'un motif de signalement. */
export function reasonLabel(reason, t) {
  const map = {
    harassment: t.reasonHarassment,
    spam: t.reasonSpam,
    hate: t.reasonHate,
    inappropriate: t.reasonInappropriate,
    other: t.reasonOther,
  };
  return map[reason] || map.other;
}

/** Message lisible pour une erreur Supabase du module messagerie. */
export function describeMessagesError(error, t) {
  const message = error?.message || '';
  const code = error?.code || '';
  if (error?.status === 0 || /failed to fetch|load failed|networkerror|fetch failed/i.test(message)) return t.errNetwork;
  if (code === '42501' || code === 'PGRST301' || error?.status === 401 || /row-level security|jwt|permission denied/i.test(message)) return t.errSignedOut;
  if (/direct_message_blocked/i.test(message)) return t.errBlocked;
  if (/direct_message_requires_friendship/i.test(message)) return t.errNotFriends;
  if (/direct_message_rate_limited/i.test(message)) return t.errRateLimited;
  if (/direct_message_(empty|too_long)/i.test(message)) return t.errEmpty;
  return t.errGeneric;
}
